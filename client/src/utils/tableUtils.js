function flattenCell(value) {
  if (value === null || value === undefined) return "";
  return String(value)
    .replace(/[\t\n\r]+/g, " ")
    .trim();
}

export function buildTsv(headers, rows) {
  const lines = [(headers || []).map(flattenCell).join("\t")];
  for (const row of rows || []) {
    if (!Array.isArray(row)) continue;
    lines.push(row.map(flattenCell).join("\t"));
  }
  return lines.join("\n");
}

export function escapeHtml(value) {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function buildResultHtml(headers, rows) {
  const colCount = headers?.length ?? 0;
  let rowCount = 0;
  let bodyRows = "";

  for (const row of rows || []) {
    if (!Array.isArray(row)) continue;
    rowCount += 1;
    const cells = row
      .slice(0, colCount)
      .map((cell) => `<td>${escapeHtml(flattenCell(cell))}</td>`)
      .join("");
    bodyRows += `<tr>${cells}</tr>`;
  }

  const headCells = (headers || [])
    .map((header) => `<th>${escapeHtml(header ?? "")}</th>`)
    .join("");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>AskDB Result — ${rowCount} rows</title>
<style>
  * { box-sizing: border-box; margin: 0; padding: 0; }
  body {
    background: #131318;
    color: #e4e1e9;
    font-family: Inter, ui-sans-serif, system-ui, sans-serif;
    padding: 24px;
  }
  h1 { font-size: 16px; font-weight: 700; color: #e4e1e9; margin-bottom: 16px; }
  h1 span { color: #918fa1; font-weight: 500; font-size: 12px; margin-left: 8px; }
  .wrap {
    border: 1px solid rgba(70, 69, 85, 0.45);
    border-radius: 12px;
    overflow: auto;
    max-height: calc(100vh - 80px);
  }
  table { border-collapse: collapse; width: 100%; font-size: 13px; }
  thead th {
    position: sticky;
    top: 0;
    z-index: 1;
    background: #0e0e13;
    color: #c3c0ff;
    font-family: "JetBrains Mono", ui-monospace, monospace;
    font-size: 10px;
    letter-spacing: 0.08em;
    text-transform: uppercase;
    text-align: left;
    padding: 10px 14px;
    border-bottom: 1px solid rgba(70, 69, 85, 0.45);
    white-space: nowrap;
  }
  td {
    color: #c7c4d8;
    padding: 9px 14px;
    border-bottom: 1px solid rgba(70, 69, 85, 0.25);
    vertical-align: top;
    word-break: break-word;
    max-width: 420px;
    white-space: pre-wrap;
  }
  tbody tr:hover { background: rgba(195, 192, 255, 0.05); }
  tbody tr:last-child td { border-bottom: none; }
  .note { margin-top: 12px; font-size: 11px; color: #625f75; }
</style>
</head>
<body>
  <h1>AskDB Result<span>${rowCount} row${rowCount === 1 ? "" : "s"} · read-only query result</span></h1>
  <div class="wrap">
    <table>
      <thead><tr>${headCells}</tr></thead>
      <tbody>${bodyRows}</tbody>
    </table>
  </div>
  <p class="note">Generated by AskDB.</p>
</body>
</html>`;
}

export function openResultInNewTab(headers, rows) {
  const html = buildResultHtml(headers, rows);
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const opened = window.open(url, "_blank");

  if (opened) {
    URL.revokeObjectURL(url);
  } else {
    // Popup blocked: revoke later so a browser-initiated open (from the
    // blocked-popup prompt) can still resolve the URL.
    window.setTimeout(() => URL.revokeObjectURL(url), 60000);
  }
  return Boolean(opened);
}
